/** Typed client for the Tier0 conversation API. */

export type AgentName = "front_desk" | "troubleshoot" | "status" | "human_agent";
export type ConversationStatus = "completed" | "approval_required" | "blocked" | "with_human";

export interface AgentMessage {
  agent: AgentName;
  text: string;
  /** The line's place in the call transcript; used to fetch its audio. Blocked replies have none. */
  index?: number;
}

export interface Health {
  database: "up" | "down";
  voice?: { openai: boolean };
}

export interface CheckApproval {
  callId: string;
  tool: string;
  title: string;
  readOnly: true;
  selfCheck: string;
}

export interface ChangeApproval {
  callId: string;
  action: "reschedule_visit";
  description: string;
}

export type ApprovalItem = CheckApproval | ChangeApproval;

export interface Handoff {
  from: AgentName;
  to: AgentName;
  reason: string;
  at: string;
}

export interface Customer {
  firstName: string | null;
  laptop: string | null;
}

export interface CaseSummary {
  findings: string[];
  likelyCause: string | null;
  fixesTried: string[];
  hardwareIssues: string[];
}

export interface Escalation {
  from: AgentName;
  reason: string;
  at: string;
  customer: Customer | null;
  caseSummary?: CaseSummary;
}

export interface Fix {
  title: string;
  steps: string[];
  doneBy: "customer" | "technician";
}

export interface TroubleshootDecision {
  nextAction: string;
  findings: string[];
  likelyCause: string | null;
  confidence: number;
  fixes: Fix[];
  escalationReason: string | null;
  case?: { status: string; fixAttempts: number; checksRun: number };
}

export interface ConversationReply {
  sessionId: string;
  status: ConversationStatus;
  activeAgent: AgentName;
  messages: AgentMessage[];
  verified: boolean;
  customer: Customer | null;
  toolsRun: { agent: AgentName; tool: string }[];
  approval?: { agent: AgentName; items: ApprovalItem[] };
  handoffs: Handoff[];
  decisions: { agent: AgentName; decision: unknown }[];
  escalation?: Escalation;
  debug?: Record<string, unknown>[];
}

export class ApiError extends Error {
  constructor(
    message: string,
    readonly status: number,
    readonly code?: string,
  ) {
    super(message);
  }
}

async function request<T>(path: string, body?: unknown): Promise<T> {
  let res: Response;
  try {
    res = await fetch(`/api${path}`, {
      method: "POST",
      headers: body === undefined ? undefined : { "Content-Type": "application/json" },
      body: body === undefined ? undefined : JSON.stringify(body),
    });
  } catch {
    throw new ApiError("Can't reach the Tier0 server. Is it running?", 0);
  }

  const json = await res.json().catch(() => null);
  if (!res.ok || !json?.success) {
    const message =
      res.status === 429 ? "You're sending messages too quickly. Please wait a moment." : (json?.message ?? "Something went wrong");
    throw new ApiError(message, res.status, json?.error?.code);
  }
  return json.data as T;
}

export const api = {
  health: async (): Promise<Health> => {
    const res = await fetch("/api/health");
    return (await res.json()).data as Health;
  },
  start: () => request<ConversationReply>("/conversations"),
  send: (sessionId: string, message: string, interrupted = false) =>
    request<ConversationReply>(`/conversations/${sessionId}/messages`, { message, ...(interrupted && { interrupted }) }),
  answer: (sessionId: string, approve: boolean) =>
    request<ConversationReply>(`/conversations/${sessionId}/approval`, { approve }),
  /** Audio of one agent line, generated by OpenAI on the server. */
  speechUrl: (sessionId: string, index: number) => `/api/conversations/${sessionId}/speech/${index}`,
  transcribe: async (sessionId: string, wav: Blob): Promise<string> => {
    const res = await fetch(`/api/conversations/${sessionId}/transcribe`, {
      method: "POST",
      headers: { "Content-Type": "audio/wav" },
      body: wav,
    });
    const json = await res.json().catch(() => null);
    if (!res.ok || !json?.success) throw new ApiError(json?.message ?? "Couldn't transcribe that", res.status);
    return (json.data.text as string) ?? "";
  },
};

export const isCheckApproval = (item: ApprovalItem): item is CheckApproval => "tool" in item;
